def _bil(xg, yg, Z, x, y):
    """bilinear in (x along columns, y along rows), clamped."""
    x = np.clip(x, xg[0], xg[-1])
    y = np.clip(y, yg[0], yg[-1])
    i = min(max(np.searchsorted(xg, x) - 1, 0), len(xg) - 2)
    j = min(max(np.searchsorted(yg, y) - 1, 0), len(yg) - 2)
    a = (x - xg[i])/(xg[i+1] - xg[i])
    b = (y - yg[j])/(yg[j+1] - yg[j])
    return ((1-a)*(1-b)*Z[j, i] + a*(1-b)*Z[j, i+1] + (1-a)*b*Z[j+1, i] + a*b*Z[j+1, i+1])


def rot(sp, T, nc, Nt):
    """returns L, L0, L_LTE, n_half."""
    lt, ln = np.log10(T), np.log10(max(Nt, 1.))
    if sp == 'H2':
        L0 = 10**np.interp(lt, H_TAB[:, 0], -H_TAB[:, 1])
        LL = 10**np.interp(lt, H_TAB[:, 0], -H_TAB[:, 2])
        nh = 10**np.interp(lt, H_TAB[:, 0], H_TAB[:, 3])
        al = np.interp(lt, H_TAB[:, 0], H_TAB[:, 4])
    else:
        Tg, Ng, L0g, LLg, NHg, ALg = ((W_T, W_N, W_L0, W_LL, W_NH, W_AL) if sp == 'H2O' else
                                      (C_T, C_N, C_L0, C_LL, C_NH, C_AL))
        lTg = np.log10(Tg)
        L0 = 10**np.interp(np.clip(lt, lTg[0], lTg[-1]), lTg, L0g)
        LL = 10**_bil(lTg, Ng, LLg, lt, ln)
        nh = 10**_bil(lTg, Ng, NHg, lt, ln)
        al = _bil(lTg, Ng, ALg, lt, ln)
    inv = 1/L0 + nc/LL + (1/L0)*(nc/nh)**al*(1 - nh*L0/LL)
    return 1/inv, L0, LL, nh


def vib(sp, T, nc, Nt):
    """returns L, L0, L_LTE, beta_band (= L_LTE(N)/L_LTE(thin)), A_eff (1/s)."""
    if sp == 'H2':
        L0 = 1.19e-24*np.sqrt(T)*np.exp(-18100./(T + 1190.))*np.exp(-5987./T)
        LL = 1.10e-18*np.exp(-6744./T)
        bet = 1.
        LLthin = LL
    else:
        Z = VW if sp == 'H2O' else VC
        E = EV_K[sp]
        if sp == 'H2O':
            L0 = 1.03e-26*T*np.exp(-47.5/T**(1/3))*np.exp(-2325./T)
        else:
            L0 = 1.83e-26*T*np.exp(-68.0/T**(1/3))*np.exp(-3080./T)
        lT = np.log10(V_T)
        lt, ln = np.log10(T), np.log10(max(Nt, 1.))
        LL = 10**_bil(lT, V_N, Z, lt, ln)*np.exp(-E/T)
        LLthin = 10**_bil(lT, V_N, Z, lt, 13.)*np.exp(-E/T)
        bet = LL/LLthin
    Aeff = LLthin*np.exp(EV_K[sp]/T)/HNU[sp]
    inv = 1/L0 + nc/LL
    return 1/inv, L0, LL, bet, Aeff
